import { writeFileSync, readFileSync } from 'node:fs';
import { values, responsive } from './src/values.ts';

const rule = (selector, entries) => `${selector} {\n${Object.entries(entries).map(([key, value]) => `  ${key}: ${value};`).join('\n')}\n}`;
const css = '/* Generated by build.mjs from src/values.ts. Do not edit. */\n' +
  rule('.finder-shell', values) + '\n' + responsive.map(({ selector, media, values }) =>
    `\n@media ${media} {\n${rule(selector, values)}\n}\n`).join('');
const target = new URL('./tokens.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) throw new Error('Run npm run build:tokens to regenerate legacy CSS');
} else {
  writeFileSync(target, css);
}
